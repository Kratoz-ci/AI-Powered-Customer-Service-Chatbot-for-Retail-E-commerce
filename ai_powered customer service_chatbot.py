# =============================================
# Multi-Chat State Logic
# =============================================

def make_new_chat_id():
    return str(uuid.uuid4())

def new_chat(chats, current_id):
    new_id = make_new_chat_id()
    chats[new_id] = {"title": "New Chat", "messages": []}
    choices = get_history_choices(chats)
    return chats, new_id, [], gr.update(choices=choices, value=new_id)

def get_history_choices(chats):
    # Newest chats first
    items = list(chats.items())
    items.reverse()
    return [(data["title"], cid) for cid, data in items]

def switch_chat(selected_id, chats):
    if selected_id is None or selected_id not in chats:
        return [], selected_id
    return chats[selected_id]["messages"], selected_id

def send_message(message, chats, current_id):
    if not message or not message.strip():
        choices = get_history_choices(chats)
        current_messages = chats.get(current_id, {}).get("messages", [])
        return current_messages, chats, current_id, gr.update(choices=choices, value=current_id), ""

    # If no active chat, create one
    if current_id is None or current_id not in chats:
        current_id = make_new_chat_id()
        chats[current_id] = {"title": "New Chat", "messages": []}

    response = chat_with_bot(message, chats[current_id]["messages"])

    chats[current_id]["messages"].append({"role": "user", "content": message})
    chats[current_id]["messages"].append({"role": "assistant", "content": response})

    # Auto-title the chat from the first user message
    if chats[current_id]["title"] == "New Chat":
        short_title = message.strip()
        if len(short_title) > 28:
            short_title = short_title[:28] + "..."
        chats[current_id]["title"] = short_title

    choices = get_history_choices(chats)
    return chats[current_id]["messages"], chats, current_id, gr.update(choices=choices, value=current_id), ""


