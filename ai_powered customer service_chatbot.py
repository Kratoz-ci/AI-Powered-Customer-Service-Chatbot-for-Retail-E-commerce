def get_best_response(user_message):
    user_message = user_message.lower()

    # Check for exact keyword matches first
    for key, value in knowledge_base.items():
        for q in value["questions"]:
            if q in user_message:
                return value["response"]

    # If no keyword match, use default
    return knowledge_base["default"]["response"]

def chat_with_bot(message, history):
    response = get_best_response(message)

    # Add personalized touch
    if "order" in message.lower():
        response += " Please share your order number."
    elif "price" in message.lower() or "cost" in message.lower():
        response += " Check our website for current promotions!"

    return response

